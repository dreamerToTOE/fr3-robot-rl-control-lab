#!/usr/bin/env python3
"""RL05 —— 从已有产物补齐 metadata.json（用于修复训练期 JSON 序列化失败留下的缺档）。

不需要 Isaac Sim，只用 SB3 + torch 即可运行：
    cd /home/ubuntu2004/isaacsim-4.5.0
    PYTHONPATH=<RL05>/.pydeps ./python.sh <RL05>/scripts/repair_metadata.py --run-id sac_seed42_v2
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

RL05 = Path(__file__).resolve().parents[1]
RESULTS = RL05 / "results" / "rl05"


def _jsonable(v):
    try:
        import numpy as _np
        import torch as _torch
        if isinstance(v, _torch.Tensor):
            return v.detach().cpu().tolist()
        if isinstance(v, _np.ndarray):
            return v.tolist()
        if isinstance(v, _np.generic):
            return v.item()
    except Exception:
        pass
    return v if isinstance(v, (int, float, str, bool, list, dict, type(None))) else str(v)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-id", required=True)
    args = ap.parse_args()
    run_dir = RESULTS / args.run_id
    cfg = json.loads((run_dir / "config.json").read_text())
    algo = cfg["algo"]

    # progress.csv 提供真实步数与 wall time
    steps = elapsed = episodes = eps_success = None
    prog = run_dir / "logs" / "progress.csv"
    if prog.exists():
        rows = list(csv.DictReader(open(prog)))
        if rows:
            d = rows[-1]
            steps = int(float(d["time/total_timesteps"]))
            elapsed = float(d["time/time_elapsed"])
            episodes = int(float(d.get("time/episodes", 0) or 0))
            eps_success = float(d.get("rollout/success_rate", 0) or 0)

    # 训练 episode 统计
    n_ep = n_succ = None
    tm = run_dir / "train_metrics.csv"
    if tm.exists():
        ep_rows = list(csv.DictReader(open(tm)))
        n_ep = len(ep_rows)
        n_succ = sum(int(float(r["is_success"])) for r in ep_rows)

    versions, hyper = {}, {}
    try:
        import gymnasium
        import numpy as np
        import stable_baselines3
        import torch
        versions = {"python": sys.version.split()[0], "torch": torch.__version__,
                    "cuda": bool(torch.cuda.is_available()),
                    "gpu": torch.cuda.get_device_name(0) if torch.cuda.is_available() else None,
                    "gymnasium": gymnasium.__version__,
                    "stable_baselines3": stable_baselines3.__version__,
                    "numpy": np.__version__}
        from stable_baselines3 import PPO, SAC
        model = (SAC if algo == "sac" else PPO).load(str(run_dir / "final_model.zip"), device="cpu")
        for attr in ("get_params", "get_parameters"):
            fn = getattr(model, attr, None)
            if callable(fn):
                try:
                    hyper = {k: _jsonable(v) for k, v in fn().items() if k not in ("policy", "env", "device")}
                    break
                except Exception:
                    continue
        if steps is None:
            steps = int(model.num_timesteps)
    except Exception as exc:
        hyper = {"_error": str(exc)}

    meta = {
        "algo": algo, "run_id": args.run_id, "seed": cfg.get("seed"),
        "total_timesteps_requested": cfg.get("total_timesteps"),
        "total_timesteps_actual": steps,
        "wall_time_s": round(elapsed, 2) if elapsed is not None else None,
        "env_steps_per_s": round(steps / elapsed, 2) if (steps and elapsed) else None,
        "episodes": n_ep, "episode_successes": n_succ,
        "train_success_rate": (n_succ / n_ep) if n_ep else None,
        "sb3_logged_episodes": episodes, "sb3_logged_success_rate": eps_success,
        "sim": {"physics_dt": cfg.get("physics_dt"), "decimation": cfg.get("decimation"),
                "control_hz": 1.0 / (cfg.get("physics_dt", 1 / 120) * cfg.get("decimation", 4)),
                "num_envs": 1, "max_control_steps": cfg.get("max_control_steps")},
        "reward_weights": {k: cfg.get(k) for k in ("progress_coef", "success_bonus",
                                                  "action_penalty_coef", "smoothness_coef")},
        "versions": versions, "hyperparams": hyper,
        "config_path": f"configs/{Path(cfg.get('config_path', '')).name}" if cfg.get("config_path") else None,
        "final_model": f"results/rl05/{args.run_id}/final_model.zip",
        "checkpoints": sorted(p.name for p in (run_dir / "checkpoints").glob("*.zip")),
        "_note": "regenerated by scripts/repair_metadata.py after a JSON-serialization failure "
                 "in the original run (torch Tensor in hyperparams).",
    }
    (run_dir / "metadata.json").write_text(json.dumps(meta, ensure_ascii=False, indent=2, default=str),
                                          encoding="utf-8")
    print("METADATA_OK", args.run_id, "steps=", steps, "wall_s=", meta["wall_time_s"],
          "eps/s=", meta["env_steps_per_s"], "train_succ=", meta["train_success_rate"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
